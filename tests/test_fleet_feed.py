        self.assertEqual((self.row(doc, "shop")["working"], self.row(doc, "shop")["busy_sessions"]), (True, 2))
        self.assertEqual((self.row(doc, "hub")["working"], self.row(doc, "hub")["busy_sessions"]), (False, 0))

